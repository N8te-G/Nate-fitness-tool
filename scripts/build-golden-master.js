// Builds Nates_HeartMatch_Golden_Master.html: a single, self-contained copy of index.html
// with the stylesheet, libraries and icons embedded, so it works when opened directly as a file.
// Usage: npm run build:golden
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const read = f => fs.readFileSync(path.join(root, f));
const dataUri = (f, type) => `data:${type};base64,${read(f).toString('base64')}`;

let html = read('index.html').toString();

function replaceOnce(find, replacement) {
    const count = html.split(find).length - 1;
    if (count !== 1) throw new Error(`Expected exactly one match for: ${find} (found ${count})`);
    html = html.replace(find, () => replacement);
}
const safeScript = js => js.replace(/<\/script/gi, '<\\/script');

// Leaflet CSS with its images embedded
let leafletCss = read('vendor/leaflet/leaflet.css').toString()
    .replace(/url\(images\/([\w-]+\.png)\)/g, (m, f) => `url(${dataUri('vendor/leaflet/images/' + f, 'image/png')})`);

replaceOnce('<link rel="stylesheet" href="./vendor/tailwind.css">',
    `<style>/* Tailwind (prebuilt) */\n${read('vendor/tailwind.css')}\n</style>`);
replaceOnce('<link rel="stylesheet" href="./vendor/leaflet/leaflet.css" />',
    `<style>/* Leaflet 1.9.4 */\n${leafletCss}\n</style>`);
replaceOnce('<script src="./vendor/chart.umd.min.js"></script>',
    `<script>/* Chart.js 4.4.1 (MIT) */\n${safeScript(read('vendor/chart.umd.min.js').toString())}\n</script>`);
replaceOnce('<script src="./vendor/leaflet/leaflet.js"></script>',
    `<script>/* Leaflet 1.9.4 (BSD-2-Clause) */\n${safeScript(read('vendor/leaflet/leaflet.js').toString())}\n</script>`);

// Icons embedded as data URIs
replaceOnce('href="./apple-touch-icon.png"', `href="${dataUri('apple-touch-icon.png', 'image/png')}"`);
replaceOnce('href="./icon.svg"', `href="${dataUri('icon.svg', 'image/svg+xml')}"`);
replaceOnce('<link rel="icon" type="image/png" sizes="192x192" href="./icon-192.png">', '');
replaceOnce('<img src="./icon-192.png"', `<img src="${dataUri('icon-192.png', 'image/png')}"`);

// Nothing should still point at a local file in a tag
const leftovers = html.match(/(?:src|href)="\.\/(?!manifest\.json)[^"]*"/g);
if (leftovers) throw new Error('Unembedded local references: ' + leftovers.join(', '));

html = html.replace('<head>', '<head>\n    <!-- Golden Master: self-contained build of index.html (generated by scripts/build-golden-master.js) -->');
const out = path.join(root, 'Nates_HeartMatch_Golden_Master.html');
fs.writeFileSync(out, html);
console.log(`Wrote ${path.basename(out)} (${(html.length / 1024).toFixed(0)} KB)`);
